import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {readFileSync} from 'node:fs';
import {forestShrubLeafData,forestMushroomCapData} from '../forest-art-ecology.js';
import {forestEcologyLayout,createForestEcology} from '../forest-ecology.js';
import {forestFloorLayout,forestFloorBudget,createForestFloor} from '../forest-floor.js';
import {createForestLayout,forestColliders,createWhisperingForest} from '../whispering-forest.js';

test('new understory leaflets are curved, shaded and remain exactly 18 triangles',()=>{
 const leaf=forestShrubLeafData();
 assert.equal(leaf.triangles,18);
 assert.equal(leaf.positions.length,162);
 assert.equal(leaf.colors.length,leaf.positions.length);
 assert.deepEqual(forestShrubLeafData(),leaf);
 assert.ok(leaf.colors.every(c=>c>=0&&c<=1));
 assert.ok(new Set(leaf.colors.filter((_,i)=>i%3===1)).size>=4);
 const maxHeight=Math.max(...leaf.positions.filter((_,i)=>i%3===1));
 assert.ok(maxHeight>.65&&maxHeight<1.1);
});
test('mushroom caps have rounded rims and dark gills, no transparent geometry',()=>{
 const cap=forestMushroomCapData();
 assert.equal(cap.triangles,108);
 assert.equal(cap.positions.length,108*9);
 assert.equal(cap.colors.length,cap.positions.length);
 assert.deepEqual(cap,forestMushroomCapData());
 assert.ok(cap.colors.every(x=>Number.isFinite(x)&&x>=0&&x<=1));
 assert.ok(Math.max(...cap.positions.filter((_,i)=>i%3===1))>.4);
 assert.ok(Math.min(...cap.positions.filter((_,i)=>i%3===1))<-.2);
 assert.ok(new Set(cap.colors.filter((_,i)=>i%3===0)).size>=4);
});
test('visual ecology keeps all fixed shrub, mushroom, wildlife and stone anchors',()=>{
 const old=forestEcologyLayout(),colliders=forestColliders(),trees=createForestLayout();
 const scene=new THREE.Scene();
 const ecology=createForestEcology(THREE,{scene,radius:261,heightAt:()=>0});
 assert.deepEqual(ecology.layout,old);
 assert.equal(old.shrubs.length,500);
 assert.equal(old.fungi.length,145);
 assert.equal(old.rocks.length,190);
 const shrub=scene.getObjectByName('forest-shrubs');
 const cap=scene.getObjectByName('forest-mushroom-caps');
 const stem=scene.getObjectByName('forest-mushroom-stems');
 assert.ok(shrub?.isInstancedMesh&&cap?.isInstancedMesh&&stem?.isInstancedMesh);
 assert.equal(shrub.instanceMatrix.count,500);
 assert.equal(cap.instanceMatrix.count,145);
 assert.equal(stem.instanceMatrix.count,145);
 assert.equal(shrub.geometry.attributes.position.count,54);
 assert.equal(cap.geometry.attributes.position.count,324);
 assert.ok(shrub.material.vertexColors&&cap.material.vertexColors&&stem.material.vertexColors);
 assert.equal(scene.children.filter(x=>x.isInstancedMesh&&x.name.startsWith('forest-')).length,5);
 assert.deepEqual(forestColliders(),colliders);
 assert.deepEqual(createForestLayout(),trees);
});
test('existing moss sheets and buttresses retain budgets with visible colour gradients',()=>{
 const roots=forestColliders(),trees=createForestLayout(),floorPoints=forestFloorLayout();
 const scene=new THREE.Scene(),forestScene=new THREE.Scene();
 const floor=createForestFloor(THREE,{scene,radius:261,heightAt:()=>0});
 createWhisperingForest(THREE,{scene:forestScene,radius:261,heightAt:()=>0,r2Vegetation:true,artRemaster:true});
 const moss=scene.getObjectByName('forest-floor-moss-no-collision');
 const root=forestScene.getObjectByName('forest-buttress-roots');
 assert.equal(floor.drawCalls,2);
 assert.equal(moss.geometry.attributes.position.count,floorPoints.moss.length*9*3);
 assert.equal(root.geometry.attributes.position.count,30);
 assert.ok(root.geometry.getAttribute('color'));
 assert.ok(root.material.vertexColors);
 assert.equal(root.instanceMatrix.count,400);
 assert.deepEqual(forestFloorBudget('balanced'),{moss:410,litter:565});
 assert.deepEqual(forestColliders(),roots);
 assert.deepEqual(createForestLayout(),trees);
});
